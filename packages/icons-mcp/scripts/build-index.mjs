/**
 * Builds the compact MCP index from @vaultui/icons generated data.
 *
 * Input : packages/icons/generated/manifest.json
 * Output: packages/icons-mcp/src/generated/mcp-index.ts
 *
 * The index keeps only what tool handlers need; SVG payload stays in the site's
 * /data shards and is fetched on demand.
 */

import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const pkgRoot = path.resolve(here, "..");
const iconsGenerated = path.resolve(pkgRoot, "..", "icons", "generated");
const outDir = path.join(pkgRoot, "src", "generated");
const outFile = path.join(outDir, "mcp-index.ts");

function shardLetter(name) {
  const first = name[0] ?? "";
  return /[a-z]/i.test(first) ? first.toLowerCase() : "_";
}

let manifest;
try {
  manifest = JSON.parse(await readFile(path.join(iconsGenerated, "manifest.json"), "utf8"));
} catch {
  console.error(
    "Missing packages/icons/generated/manifest.json. Run `pnpm --filter @vaultui/icons build` first.",
  );
  process.exit(1);
}

const icons = manifest.icons.map((icon) => ({
  name: icon.name,
  category: icon.category,
  tags: Array.isArray(icon.tags) ? icon.tags : [],
  aliases: Array.isArray(icon.aliases) ? icon.aliases : [],
  letter: shardLetter(icon.name),
}));

const index = {
  generatedAt: new Date().toISOString(),
  total: manifest.total,
  weights: manifest.weights,
  categories: manifest.categories.map(({ id, label, blurb, count }) => ({ id, label, blurb, count })),
  icons,
};

const header =
  "// Generated by scripts/build-index.mjs. Do not edit by hand.\n" +
  'import type { McpIndex } from "../core.js";\n\n';

await mkdir(outDir, { recursive: true });
await writeFile(outFile, `${header}export const MCP_INDEX: McpIndex = ${JSON.stringify(index)};\n`);

console.log(`MCP index: ${icons.length} icons, ${index.categories.length} categories -> ${path.relative(pkgRoot, outFile)}`);
